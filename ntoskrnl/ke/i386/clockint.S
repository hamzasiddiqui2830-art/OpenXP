/*

* VOID
* KeProfileInterrupt(
* 
    IN PKTRAP_FRAME TrapFrame
  
* 
    )
  
*
* This procedure rearranges the arguments to pass a source of 0 to
* KeProfileInterruptWithSource.
  */

FUNC KeProfileInterrupt, 1


    popl    %eax
    popl    %ebx

    pushl   $0
    pushl   %ebx
    pushl   %eax

    jmp     _KeProfileInterruptWithSource


ENDPROC KeProfileInterrupt

/*

* 
*
* VOID
* KeProfileInterruptWithSource(
* 
    IN PKTRAP_FRAME TrapFrame,
  
* 
    IN KPROFILE_SOURCE ProfileSource
  
* 
    )
  
*
* Routine Description:
*
* This procedure is the ISR for the multiple-source profile interrupt.
*
* Since no x86 HAL currently implements any source other than the
* clock interrupt, this routine is just a stub that calls
* KeProfileInterrupt.
*
* Arguments:
*
* Return Address (esp)
*
* TrapFrame (esp+4) - supplies pointer to profile trap frame
*
* ProfileSource (esp+8) - supplies source of profile interrupt
*
* Environment:
*
* IRQL = KiProfileIrql
*
* Return Value:
*
* None.
*
* WARNING: Uses ALL registers
*
* 

*/

#define kipieip  TsEip(%ebp)
#define kipsegcs TsSegCs(%ebp)
#define kipeflags TsEFlags(%ebp)

FUNC KeProfileInterruptWithSource, 2


    movl    4(%esp), %ebp

    incl    PbInterruptCount+PcPrcbData(PCR)

    cmpl    $0, _PPerfGlobalGroupMask
    je      kipi03


/*

* Add profile interrupt to perfinfo.
  */

  
   movl    8(%esp), %ecx
   movl    kipieip, %edx

   FASTCALL PerfProfileInterrupt

   movl    4(%esp), %ebp
  

/*

* Reset EIP if it is found to be within the kernel interlocked pop entry
* slist code. Otherwise profile objects (queued by the user) could be
* used to corrupt a kernel slist.
  */

kipi03:


    cmpl    $_ExpInterlockedPopEntrySListResume, kipieip
    jb      kipi04

    cmpl    $_ExpInterlockedPopEntrySListEnd, kipieip
    ja      kipi04

    movl    %ebp, %ecx
    FASTCALL KiCheckForSListAddress


kipi04:

#ifndef NT_UP


    leal    _KiProfileLock, %eax


kipi05:


    ACQUIRE_SPINLOCK eax, kipi96


#endif

/*

* Update profile data.
*
* NOTE:
* System and Process update loops are duplicates, to avoid overhead
* of call instruction in what could be very high frequency interrupt.
* Be sure to update both loops for changes.
*
* NOTE:
* The process loop contains code to update segment profile objects.
* This code is not present in the system loop, because we do not
* allow attachment of profile objects for non-flat segments on a
* system wide basis.
*
* NOTE:
* Profiling in V86 mode is handled by converting the CS:IP value to
* a linear address (CS << 4 + IP).
  */

  
   incl    ProfileCount
  

/*

* Update system profile entries.
  */

  
   movl    kipieip, %ebx

   movl    $_KiProfileListHead, %edx

   movl    LsFlink(%edx), %esi
  

#ifndef NT_UP


    movl    PCR[PcSetMember], %edi


#endif


    movl    8(%esp), %ecx

    cmpl    %edx, %esi
    je      kipi30


/*

* (ebx) = sample program counter
* (esi) -> profile object
  */

  
   .align 4
  

kipi10:


    cmpl    PfRangeBase-PfProfileListEntry(%esi), %ebx
    jb      kipi20

    cmpl    PfRangeLimit-PfProfileListEntry(%esi), %ebx
    jae     kipi20

    cmpw    PfSource-PfProfileListEntry(%esi), %cx
    jne     kipi20


#ifndef NT_UP


    testl   PfAffinity-PfProfileListEntry(%esi), %edi
    jz      kipi20


#endif

/*

* RangeBase <= program counter < RangeLimit, we have a hit.
  */

  
   subl    PfRangeBase-PfProfileListEntry(%esi), %ebx

   movb    PfBucketShift-PfProfileListEntry(%esi), %cl

   shrl    %cl, %ebx

   andl    $~3, %ebx

   movl    PfBuffer-PfProfileListEntry(%esi), %edi

   incl    (%edi,%ebx,1)

   movl    kipieip, %ebx

   movl    8(%esp), %ecx
  

#ifndef NT_UP


    movl    PCR[PcSetMember], %edi


#endif

/*

* Go to next entry.
  */

  
   .align 4
  

kipi20:


    movl    LsFlink(%esi), %esi

    cmpl    %edx, %esi
    jne     kipi10


/*

* Update process profile entries.
*
* (ebx) = sample program counter
  */

  
   .align 4
  

kipi30:


    movl    PCR[PcPrcbData+PbCurrentThread], %eax

    movl    ThApcState+AsProcess(%eax), %eax

    leal    PrProfileListHead(%eax), %edx

    movl    LsFlink(%edx), %esi

    cmpl    %edx, %esi
    je      kipi60


/*

* Check for 16 bitness.
  */

  
   movzwl  kipsegcs, %ecx

   testl   $EFLAGS_V86_MASK, kipeflags
   jnz     kipi100

   cmpw    $KGDT_R0_CODE, %cx
   je      kipi40

   cmpw    $(KGDT_R3_CODE | RPL_MASK), %cx
   jne     kipi110
  

/*

* (ebx) = sample program counter
* (esi) -> profile object
  */

  
   .align 4
  

kipi40:


    cmpw    $0, PfSegment-PfProfileListEntry(%esi)
    jne     kipi50

    cmpl    PfRangeBase-PfProfileListEntry(%esi), %ebx
    jb      kipi50

    cmpl    PfRangeLimit-PfProfileListEntry(%esi), %ebx
    jae     kipi50

    movl    8(%esp), %ecx

    cmpw    PfSource-PfProfileListEntry(%esi), %cx
    jne     kipi50


#ifndef NT_UP


    movl    PCR[PcSetMember], %edi

    testl   PfAffinity-PfProfileListEntry(%esi), %edi
    jz      kipi50


#endif

/*

* RangeBase <= program counter < RangeLimit, we have a hit.
  */

  
   subl    PfRangeBase-PfProfileListEntry(%esi), %ebx

   movb    PfBucketShift-PfProfileListEntry(%esi), %cl

   shrl    %cl, %ebx

   andl    $~3, %ebx

   movl    PfBuffer-PfProfileListEntry(%esi), %edi

   incl    (%edi,%ebx,1)

   movl    kipieip, %ebx

   movl    8(%esp), %ecx
  

/*

* Go to next entry.
  */

  
   .align 4
  

kipi50:


    movl    LsFlink(%esi), %esi

    cmpl    %edx, %esi
    jne     kipi40


    .align 4


kipi60:

#ifndef NT_UP


    leal    _KiProfileLock, %eax

    RELEASE_SPINLOCK eax


#endif


    RET_FUNC KeProfileInterruptWithSource


#ifndef NT_UP


    .align 4


kipi96:


    SPIN_ON_SPINLOCK eax, kipi05, , DbgMp


#endif

/*

* Convert V86 CS:IP to linear address.
  */

  
   .align 4
  

kipi100:


    shll    $4, %ecx
    addl    %ecx, %ebx

    jmp     kipi40


/*

* 
*
* Update segment profile objects.
*
* (ebx) = sample program counter
* (esi) -> profile object
*
* 

*/


    .align 4


kipi110:


    cmpw    PfSegment-PfProfileListEntry(%esi), %cx
    jne     kipi120

    cmpl    PfRangeBase-PfProfileListEntry(%esi), %ebx
    jb      kipi120

    cmpl    PfRangeLimit-PfProfileListEntry(%esi), %ebx
    jae     kipi120

    movl    8(%esp), %ecx

    cmpw    PfSource-PfProfileListEntry(%esi), %cx
    jne     kipi120


#ifndef NT_UP


    movl    PCR[PcSetMember], %edi

    testl   PfAffinity-PfProfileListEntry(%esi), %edi
    jnz     kipi120


#endif

/*

* RangeBase <= program counter < RangeLimit, we have a hit.
  */

  
   subl    PfRangeBase-PfProfileListEntry(%esi), %ebx

   movb    PfBucketShift-PfProfileListEntry(%esi), %cl

   shrl    %cl, %ebx

   andl    $~3, %ebx

   movl    PfBuffer-PfProfileListEntry(%esi), %edi

   incl    (%edi,%ebx,1)

   movl    kipieip, %ebx

   movw    kipsegcs, %cx
  

/*

* Go to next entry.
  */

  
   .align 4
  

kipi120:


    movl    LsFlink(%esi), %esi

    cmpl    %edx, %esi
    jne     kipi110

    jmp     kipi60


ENDPROC KeProfileInterruptWithSource

#undef kipieip
#undef kipsegcs
#undef kipeflags
