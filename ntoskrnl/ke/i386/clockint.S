/*

* 
*
* Update System Time
*
* 
*
* VOID
* KeUpdateSystemTime(
* 
    IN KIRQL PreviousIrql,
  
* 
    IN KTRAP_FRAME TrapFrame
  
* 
    )
  
*
* Routine Description:
*
* This routine is entered as the result of an interrupt generated by
* CLOCK2. Its function is to update the system time and check to
* determine if a timer has expired.
*
* N.B. This routine is executed on a single processor in a multiprocessor
* 
    system. The remainder of the processors only execute the quantum end
  
* 
    and runtime update code.
  
*
* N.B. This routine is not called, but directly jumped to. Thus, there
* 
    is no return address. It returns via the INTERRUPT_EXIT macro.
  
*
* Arguments:
*
* PreviousIrql   (esp)   - supplies previous irql of system
*
* HardwareVector (esp+4) - supplies hardware vector for EndSystemInterrupt
*
* TrapFrame      (esp+8) - supplies base of trap frame
*
* EAX is the TimeIncrement value
*
* EBP is a pointer to the trap frame
*
* Environment:
*
* IRQL = CLOCK_LEVEL
*
* Return Value:
*
* None.
*
* --
  */

FUNC KeUpdateSystemTime, 0

#if DBG


    cmpb    $0, PbSkipTick+PcPrcbData(%ecx)
    jne     kust_skiptick


#endif

/*

* Update interrupt time.
*
* N.B. The interrupt time is updated in a very strict manner so that an
* 
   interlock does not have to be used in an MP system to read time.
  

*/


    movl    $USER_SHARED_DATA, %ecx

    movl    UsInterruptTime+0(%ecx), %edi
    movl    UsInterruptTime+4(%ecx), %esi

    addl    %eax, %edi
    adcl    $0, %esi

    movl    %esi, UsInterruptTime+8(%ecx)
    movl    %edi, UsInterruptTime+0(%ecx)
    movl    %esi, UsInterruptTime+4(%ecx)


#ifndef NT_UP


    lock
    subl    %eax, _KiTickOffset


#else


    subl    %eax, _KiTickOffset


#endif


    movl    _KeTickCount+0, %eax
    movl    %eax, %ebx

    jg      kust10


/*

* Update system time.
*
* N.B. The system time is updated in a very strict manner so that an
* 
   interlock does not have to be used in an MP system to read time.
  

*/


    movl    $USER_SHARED_DATA, %ebx

    movl    UsSystemTime+0(%ebx), %ecx
    movl    UsSystemTime+4(%ebx), %edx

    addl    _KeTimeAdjustment, %ecx
    adcl    $0, %edx

    movl    %edx, UsSystemTime+8(%ebx)
    movl    %ecx, UsSystemTime+0(%ebx)
    movl    %edx, UsSystemTime+4(%ebx)

    movl    %eax, %ebx


/*

* Update tick count.
*
* N.B. The tick count is updated in a very strict manner so that an
* 
   interlock does not have to be used in an MP system to read count.
  

*/


    movl    %eax, %ecx
    movl    _KeTickCount+4, %edx

    addl    $1, %ecx
    adcl    $0, %edx

    movl    %edx, _KeTickCount+8
    movl    %ecx, _KeTickCount+0
    movl    %edx, _KeTickCount+4

    movl    %edx, USERDATA[UsTickCount+8]
    movl    %ecx, USERDATA[UsTickCount+0]
    movl    %edx, USERDATA[UsTickCount+4]


/*

* Check to determine if a timer has expired.
*
* (edi:esi) = KiInterruptTime
* (eax)     = KeTickCount.LowPart
* (ebx)     = KeTickCount.LowPart
  */

#if (TIMER_ENTRY_SIZE != 16)
#error "TIMER_ENTRY_SIZE must be 16"
#endif


    andl    $(TIMER_TABLE_SIZE - 1), %eax
    shll    $4, %eax

    cmpl    TtTime+4+_KiTimerTableListHead(%eax), %esi
    jb      kust5
    ja      kust15

    cmpl    TtTime+_KiTimerTableListHead(%eax), %edi
    jae     kust15


kust5:


    incl    %ebx

    movl    %ebx, %eax


/*

* Check to determine if a timer has expired.
*
* (edi:esi) = KiInterruptTime
* (eax)     = bucket
* (ebx)     = KeTickCount.LowPart
  */

kust10:


    andl    $(TIMER_TABLE_SIZE - 1), %eax
    shll    $4, %eax

    cmpl    TtTime+4+_KiTimerTableListHead(%eax), %esi
    jb      kustxx
    ja      kust15

    cmpl    TtTime+_KiTimerTableListHead(%eax), %edi
    jb      kustxx


kust15:

/*

* Timer has expired, put timer expiration DPC in the current processor's
* DPC queue.
*
* (ebx) = KeTickCount.LowPart
  */

  
   movl    PcPrcb+PCR, %ecx

   cmpl    $0, PbTimerRequest(%ecx)
   jne     kustxx

   movl    %esp, PbTimerRequest(%ecx)
   movl    %ebx, PbTimerHand(%ecx)

   movl    $DISPATCH_LEVEL, %ecx
   FASTCALL HalRequestSoftwareInterrupt
  

/*

* If the debugger is enabled, check if a break is requested.
  */

kustxx:


    cmpb    $0, _KdDebuggerEnabled
    jne     kust45


kust30:


    cmpl    $0, _KiTickOffset
    jg      Kust40

    movl    _KeMaximumIncrement, %eax
    addl    %eax, _KiTickOffset


/*

* Call KeUpdateRunTime to do the actual work.
*
* TOS const PreviousIrql
  */

  
   pushl   (%esp)
   call    _KeUpdateRunTime
   addl    $4, %esp
  

/*

* Do interrupt exit processing.
  */

  
   INTERRUPT_EXIT
  

Kust40:


    incl    PbInterruptCount+PcPrcbData(PCR)

    INTERRUPT_EXIT


kust45:


    call    _KdPollBreakIn

    orb     %al, %al
    jz      kust30

    pushl   $DBG_STATUS_CONTROL_C
    call    _DbgBreakPointWithStatus
    addl    $4, %esp

    jmp     kust30


#if DBG

kust_skiptick:


    movb    $0, PbSkipTick+PcPrcbData(PCR)

    jmp     Kust40


#endif

ENDPROC KeUpdateSystemTime

/*

* 
*
* Update Thread and Process Runtime
*
* 
*
* Routine Description:
*
* This routine does the actual work to update the runtime of the current
* thread, update the runtime of the current thread's process, and
* decrement the current thread's quantum.
*
* It also updates the system global counters for user and kernel mode
* time.
*
* It increments InterruptCount so that clock ticks get counted as
* interrupts.
*
* Arguments:
*
* esp+4 constant PreviousIrql
*
* ebp MUST point to the machine state frame.
*
* Return Value:
*
* None.
*
* --
  */

FUNC KeUpdateRunTime, 1


    movl    PCR[PcSelfPcr], %eax


#if DBG


    cmpb    $0, PbSkipTick+PcPrcbData(%eax)
    jne     kutp_skiptick


#endif


    pushl   %ebx

    incl    PbInterruptCount+PcPrcbData(%eax)

    movl    PbCurrentThread+PcPrcbData(%eax), %ebx

    movl    ThApcState+AsProcess(%ebx), %ecx


/*

* Determine whether the interrupted execution was user mode.
  */

  
   testl   $EFLAGS_V86_MASK, TsEFlags(%ebp)
   jne     Kutp20

   testb   $MODE_MASK, TsSegCs(%ebp)
   jne     Kutp20
  

/*

* Update the total time spent in kernel mode.
  */

  
   incl    PbKernelTime+PcPrcbData(%eax)

   cmpb    $DISPATCH_LEVEL, 8(%esp)
   jb      Kutp4

   ja      Kutp3

   cmpb    $0, PbDpcRoutineActive+PcPrcbData(%eax)
   je      Kutp4

   incl    PbDpcTime+PcPrcbData(%eax)
  

#if DBG

/*

* Check for DPCs which run for too long.
  */

  
   incl    PbDebugDpcTime+PcPrcbData(%eax)

   movl    _KiDPCTimeout, %edx

   cmpl    %edx, PbDebugDpcTime+PcPrcbData(%eax)
   jb      Kutp50
  

/*

* DPC time has exceeded the allowed quanta.
  */

  
   pushl   $_MsgDpcTimeout
   call    _DbgPrint
   addl    $4, %esp

   cmpb    $0, _KdDebuggerEnabled
   je      Kutp6

   call    _DbgBreakPoint
  

Kutp6:


    movl    PCR[PcSelfPcr], %eax

    movl    $0, PbDebugDpcTime+PcPrcbData(%eax)


#endif


    jmp     Kutp50


    .align 4


Kutp3:

/*

* Update the time spent at interrupt time for this processor.
  */

  
   incl    PbInterruptTime+PcPrcbData(%eax)

   jmp     Kutp50


   .align 4
  

Kutp4:

/*

* Update the time spent in kernel mode for the current thread and the
* current thread's process.
  */

  
   incl    ThKernelTime(%ebx)

   jmp     Kutp50
  

/*

* Update total time spent in user mode.
  */

  
   .align 4
  

Kutp20:


    incl    PbUserTime+PcPrcbData(%eax)


/*

* Update the time spent in user mode for the current thread and the
* current thread's process.
  */

  
   incl    ThUserTime(%ebx)
  

/*

* Update the DPC request rate which is computed as the average between
* the previous rate and the current rate.
  */

  
   .align 4
  

Kutp50:


    movl    PbDpcCount+PcPrcbData(%eax), %ecx
    movl    PbDpcLastCount+PcPrcbData(%eax), %edx

    movl    %ecx, PbDpcLastCount+PcPrcbData(%eax)

    subl    %edx, %ecx

    addl    PbDpcRequestRate+PcPrcbData(%eax), %ecx

    shrl    $1, %ecx

    movl    %ecx, PbDpcRequestRate+PcPrcbData(%eax)


/*

* If the current DPC queue depth is not zero, a DPC routine is not active,
* and a DPC interrupt has not been requested, then request a dispatch
* interrupt, decrement the maximum DPC queue depth, and reset the threshold
* counter if appropriate.
  */

  
   cmpl    $0, PbDpcQueueDepth+PcPrcbData(%eax)
   je      Kutp53

   cmpb    $0, PbDpcRoutineActive+PcPrcbData(%eax)
   jne     Kutp53

   cmpb    $0, PbDpcInterruptRequested+PcPrcbData(%eax)
   jne     Kutp53

   movl    $DISPATCH_LEVEL, %ecx
   FASTCALL HalRequestSoftwareInterrupt

   movl    PCR[PcSelfPcr], %eax

   movl    PbDpcRequestRate+PcPrcbData(%eax), %ecx
   movl    _KiAdjustDpcThreshold, %edx

   movl    %edx, PbAdjustDpcThreshold+PcPrcbData(%eax)

   cmpl    _KiIdealDpcRate, %ecx
   jge     Kutp55

   cmpl    $1, PbMaximumDpcQueueDepth+PcPrcbData(%eax)
   je      Kutp55

   decl    PbMaximumDpcQueueDepth+PcPrcbData(%eax)

   jmp     Kutp55
  

/*

* The DPC queue is empty or a DPC routine is active or a DPC interrupt
* has been requested. Count down the adjustment threshold and if the
* count reaches zero, then increment the maximum DPC queue depth, but
* not above the initial value and reset the adjustment threshold value.
  */

Kutp53:


    decl    PbAdjustDpcThreshold+PcPrcbData(%eax)

    jnz     Kutp55

    movl    _KiAdjustDpcThreshold, %ecx

    movl    %ecx, PbAdjustDpcThreshold+PcPrcbData(%eax)

    movl    _KiMaximumDpcQueueDepth, %ecx

    cmpl    PbMaximumDpcQueueDepth+PcPrcbData(%eax), %ecx
    je      Kutp55

    incl    PbMaximumDpcQueueDepth+PcPrcbData(%eax)


/*

* Decrement current thread quantum and check to determine if a quantum
* end has occurred.
  */

  
   .align 4
  

Kutp55:


    subb    $CLOCK_QUANTUM_DECREMENT, ThQuantum(%ebx)

    jg      Kutp75


/*

* Set quantum end flag and initiate a dispatcher interrupt on the current
* processor.
  */

  
   cmpl    PbIdleThread+PcPrcbData(%eax), %ebx
   je      Kutp75

   movb    $1, PbQuantumEnd+PcPrcbData(%eax)

   movl    $DISPATCH_LEVEL, %ecx
   FASTCALL HalRequestSoftwareInterrupt
  

Kutp75:


    popl    %ebx

    RET_FUNC KeUpdateRunTime


#if DBG

kutp_skiptick:


    movb    $0, PbSkipTick+PcPrcbData(%eax)

    RET_FUNC KeUpdateRunTime


#endif

ENDPROC KeUpdateRunTime

